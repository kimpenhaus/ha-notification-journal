const languages: Record<string, Record<Key, string>> = { en, de };

export type Localize = (key: Key, values?: Record<string, string | number>) => string;

export function localizer(language: string): Localize {
  const strings = languages[language.split("-")[0]] ?? en;
  return (key, values) =>
    strings[key].replace(/\{(\w+)\}/g, (match, name: string) =>
      values && name in values ? String(values[name]) : match,
    );
}

export function countText(localize: Localize, count: number, one: Key, many: Key): string {
  return count === 1 ? localize(one) : localize(many, { count });
}
